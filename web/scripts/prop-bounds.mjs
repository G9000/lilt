// Read alpha bounds for layout only; generated image pixels are never changed.
import { chromium } from 'playwright-core';
import { createIsolatedVite } from '../e2e/isolated-vite.mjs';
import { writeFile } from 'node:fs/promises';

const names = ['camera-black', 'camera-silver', 'camera-instant', 'camera-sage', 'coffee-latte', 'coffee-coldbrew', 'coffee-matcha', 'coffee-strawberry'];
const server = await createIsolatedVite({ logLevel: 'error' }); await server.listen();
let browser;
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage();
  await page.route('**/api/**', route => route.fulfill({ status: 503, json: {} }));
  await page.goto(server.resolvedUrls.local[0]);
  const bounds = await page.evaluate(async names => {
    const result = {};
    for (const name of names) {
      const image = new Image(); image.src = `/room/props/${name}.png`; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height;
      const ctx = canvas.getContext('2d'); ctx.drawImage(image, 0, 0);
      const data = ctx.getImageData(0, 0, canvas.width, canvas.height).data;
      let left = image.width, top = image.height, right = 0, bottom = 0;
      for (let y = 0; y < image.height; y++) for (let x = 0; x < image.width; x++) {
        if (data[(y * image.width + x) * 4 + 3] < 16) continue;
        left = Math.min(left, x); top = Math.min(top, y); right = Math.max(right, x); bottom = Math.max(bottom, y);
      }
      result[name] = { width: image.width, height: image.height, box: [left - 2, top - 2, right - left + 5, bottom - top + 5] };
    }
    return result;
  }, names);
  await writeFile(new URL('../src/room/propBounds.ts', import.meta.url), `// Generated by scripts/prop-bounds.mjs from the unmodified sprites.\nexport const PROP_BOUNDS = ${JSON.stringify(bounds, null, 2)} as const;\n`);
  console.log(bounds);
} finally { await browser?.close(); await server.close(); }
