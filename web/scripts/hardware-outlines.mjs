// Derive UI hit areas from the existing artwork; this never modifies the PNGs.
import { chromium } from 'playwright-core';
import { createIsolatedVite } from '../e2e/isolated-vite.mjs';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const server = await createIsolatedVite({ root: fileURLToPath(new URL('../', import.meta.url)), logLevel: 'error' });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage();
  await page.route('**/api/**', route => route.fulfill({ status: 503, json: {} }));
  await page.goto(server.resolvedUrls.local[0]);
  const paths = await page.evaluate(async () => {
    const W = 1672, H = 941, step = 2, cols = W / step, rows = Math.ceil(H / step);
    const canvas = document.createElement('canvas'); canvas.width = W; canvas.height = H;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    const alpha = async src => {
      const image = new Image(); image.src = src; await image.decode();
      ctx.clearRect(0, 0, W, H); ctx.drawImage(image, 0, 0, W, H);
      return ctx.getImageData(0, 0, W, H).data;
    };
    const boxes = { microphone: [560,215], 'main-frame': [840,305], 'side-frame': [1153,338] };
    const simplify = points => {
      const a = points[0], b = points.at(-1), dx = b[0] - a[0], dy = b[1] - a[1], length = dx * dx + dy * dy;
      let farthest = 0, distance = 1.2 * 1.2;
      for (let i = 1; i < points.length - 1; i++) {
        const p = points[i], t = length ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / length)) : 0;
        const d = (p[0] - a[0] - t * dx) ** 2 + (p[1] - a[1] - t * dy) ** 2;
        if (d > distance) { distance = d; farthest = i; }
      }
      return farthest ? [...simplify(points.slice(0, farthest + 1)).slice(0, -1), ...simplify(points.slice(farthest))] : [a, b];
    };
    const result = {};
    for (const id of ['microphone', 'main-frame', 'side-frame']) {
      const art = await alpha(`/room/hardware/${id === 'microphone' ? id : id.split('-')[0]}-mask.png`);
      const solid = new Uint8Array(cols * rows);
      for (let y = 0; y < rows; y++) for (let x = 0; x < cols; x++) {
        const i = (Math.min(H - 1, y * step + 1) * W + x * step + 1) * 4 + 3;
        solid[y * cols + x] = Number(art[i] > 128);
      }
      const filled = (x, y) => x >= 0 && y >= 0 && x < cols && y < rows && solid[y * cols + x];
      const edges = new Map();
      const add = (x, y, nx, ny, direction) => {
        const key = `${x},${y}`, list = edges.get(key) ?? [];
        list.push({ x: nx, y: ny, direction }); edges.set(key, list);
      };
      for (let y = 0; y < rows; y++) for (let x = 0; x < cols; x++) if (filled(x, y)) {
        if (!filled(x, y - 1)) add(x, y, x + 1, y, 0);
        if (!filled(x + 1, y)) add(x + 1, y, x + 1, y + 1, 1);
        if (!filled(x, y + 1)) add(x + 1, y + 1, x, y + 1, 2);
        if (!filled(x - 1, y)) add(x, y + 1, x, y, 3);
      }
      const contours = [];
      while (edges.size) {
        const start = edges.keys().next().value, points = [start.split(',').map(Number)];
        let key = start, direction = 0;
        do {
          const choices = edges.get(key);
          if (!choices?.length) throw new Error(`Open hardware contour: ${id}`);
          choices.sort((a, b) => [1, 0, 3, 2].indexOf((a.direction - direction + 4) % 4) - [1, 0, 3, 2].indexOf((b.direction - direction + 4) % 4));
          const next = choices.shift(); if (!choices.length) edges.delete(key);
          points.push([next.x, next.y]); key = `${next.x},${next.y}`; direction = next.direction;
        } while (key !== start);
        const area = Math.abs(points.slice(1).reduce((sum, p, i) => sum + points[i][0] * p[1] - p[0] * points[i][1], 0)) / 2;
        if (area >= 16) contours.push(simplify(points).slice(0, -1));
      }
      result[id] = contours.map(contour => {
        const points = contour.map(([x, y]) => [x * step - boxes[id][0], Math.min(H, y * step) - boxes[id][1]]);
        const toward = (a, b) => {
          const length = Math.hypot(b[0] - a[0], b[1] - a[1]), t = length ? Math.min(.5, 3 / length) : 0;
          return a.map((v, i) => +(v + (b[i] - v) * t).toFixed(1)).join(',');
        };
        const corners = points.map((p, i) => ({ p: p.join(','), before: toward(p, points[(i + points.length - 1) % points.length]), after: toward(p, points[(i + 1) % points.length]) }));
        return 'M' + corners.at(-1).after + corners.map(c => 'L' + c.before + 'Q' + c.p + ' ' + c.after).join('') + 'Z';
      }).join('');
    }
    return result;
  });
  await writeFile(new URL('../src/room/hardwareOutlinePaths.ts', import.meta.url), `// Generated by web/scripts/hardware-outlines.mjs from registered hardware alpha masks.\nimport { type Hardware } from './hardware';\n\nexport const HARDWARE_OUTLINES: Record<Hardware, string> = ${JSON.stringify(paths, null, 2)};\n`);
  console.log('Generated three hardware silhouette paths.');
} finally { await browser?.close(); await server.close(); }
