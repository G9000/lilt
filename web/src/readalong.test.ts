// node --test src/readalong.test.ts
import { test } from "node:test";
import assert from "node:assert/strict";
import { tokenize, createFollower, estimateSyllables, notesFor } from "./readalong.ts";

test("syllable estimates", () => {
  assert.equal(estimateSyllables("coffee"), 2);
  assert.equal(estimateSyllables("please"), 1);
  assert.equal(estimateSyllables("mmmmmmm"), 1);
  assert.equal(estimateSyllables("magic"), 2);
});

test("tokenize keeps punctuation with words and skips symbols", () => {
  const t = tokenize("meet · many, maybe");
  assert.deepEqual(t.filter((x) => x.word).map((x) => x.text), ["meet", "many,", "maybe"]);
});

/** Simulate speech: one loud voiced pulse per syllable, with quiet gaps. */
function speak(f: ReturnType<typeof createFollower>, syllables: number, t0 = 0, gapAfter = 0) {
  let t = t0;
  const seen: number[] = [];
  for (let s = 0; s < syllables; s++) {
    for (let k = 0; k < 6; k++) { seen.push(f.push(t, 0.12, true)); t += 0.025; }
    for (let k = 0; k < 4; k++) { seen.push(f.push(t, 0.004, false)); t += 0.025; }
  }
  for (let k = 0; k < gapAfter; k++) { seen.push(f.push(t, 0.003, false)); t += 0.025; }
  return { t, seen };
}

test("follower advances word by word with syllable beats and holds in pauses", () => {
  const tokens = tokenize("Black coffee, please.");
  const f = createFollower(tokens);
  assert.equal(f.current(), -1);
  let r = speak(f, 1);            // "Black"
  assert.equal(f.current(), 0);
  r = speak(f, 2, r.t, 40);       // "coffee" then a 1 s pause
  assert.equal(f.current(), 1, "after Black + cof-fee you're still on 'coffee'");
  const before = f.current();
  r = speak(f, 0, r.t, 40);       // silence
  assert.equal(f.current(), before, "pauses don't move the highlighter");
  speak(f, 1, r.t);               // "please"
  assert.equal(f.current(), 2, "the next beat moves to 'please'");
  const st = f.starts();
  assert.ok(st[0] !== null && st[1] !== null);
});

test("follower never runs past the last word and jumpTo re-anchors", () => {
  const f = createFollower(tokenize("one two"));
  speak(f, 9);
  assert.equal(f.current(), 1);
  f.jumpTo(0, 10);
  assert.equal(f.current(), 0);
});

test("silence alone never starts the highlighter", () => {
  const f = createFollower(tokenize("hello there"));
  for (let i = 0; i < 100; i++) f.push(i * 0.025, 0.003, false);
  assert.equal(f.current(), -1);
});

test("margin notes point at real words, max three", () => {
  const tokens = tokenize("My mother made lemon meringue on Monday morning.");
  const n = notesFor("sentences", "Keep the buzz forward on every m.", tokens);
  assert.ok(n.length <= 3 && n.length >= 1);
  assert.ok(n.every((x) => x.word === null || x.word >= 0));
  // The hint already talks about m's, so no duplicate m cue is added.
  assert.equal(n.filter((x) => /buzz/i.test(x.text)).length, 1);
  const p = notesFor("passages", "Read at an easy pace.", tokenize("Every Saturday morning, I walk down."));
  assert.equal(p.find((x) => x.word !== null)?.word, 2, "comma note anchors to 'morning,'");
});

test("calibrated on synthetic speech: estimated syllables within 15% (fixtures in analysis/tests)", async () => {
  const fs = await import("node:fs");
  const path = "../analysis/tests/fixtures/say_rms.json";
  if (!fs.existsSync(path)) return; // generated by scripts/readalong_rms.py
  const sets: { name: string; syllables: number; rms: number[] }[] = JSON.parse(fs.readFileSync(path, "utf8"));
  for (const s of sets) {
    const f = createFollower(tokenize(Array.from({ length: 80 }, () => "ba").join(" ")));
    s.rms.forEach((r, i) => f.push(i * 0.025, r, r > 0.01));
    // With 1-syllable words, the word index is the estimated syllable count (1 + gain * (beats - 1)).
    const est = f.current() + 1;
    assert.ok(Math.abs(est - s.syllables) / s.syllables <= 0.15, `${s.name}: estimated ${est}, true ${s.syllables}`);
  }
});
